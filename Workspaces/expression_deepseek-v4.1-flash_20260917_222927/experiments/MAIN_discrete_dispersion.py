def d2():
    """
    General semi-discrete linearisation.

    We keep x,t continuous and replace d/dy by a translation-invariant lattice
    operator whose action on the mode e^{i(kx + ell*j*h)} is multiplication by
    i*mu, where mu = mu_h(ell) is the (real or complex) lattice symbol and
    mu -> ell as h -> 0 for a consistent scheme.

    The point: the discrete relation has exactly the same shape with ell -> mu.
    """
    u0, v0, a, lam, k, mu, s = sp.symbols("u0 v0 a lambda k mu sigma")
    uh, vh, wh = sp.symbols("uh vh wh")
    # w = u_y  ->  what = i*mu*what_u  (lattice symbol of the discrete d/dy)
    # (1) w_t + d_x[v_x + (u+2a) w] = 0
    E1 = wh * s + (sp.I * k) ** 2 * vh + (u0 + 2 * a) * sp.I * k * wh
    # (2) v_t + d_x[(u+2a)v + w_x + 2 lam u] = 0
    E2 = vh * s + sp.I * k * (v0 * uh + (u0 + 2 * a) * vh + sp.I * k * wh + 2 * lam * uh)
    E1, E2 = sp.expand(E1), sp.expand(E2)
    sol = sp.solve(sp.Eq(E1, 0), vh)[0]
    # substitute wh = i*mu*uh as well
    E2s = sp.expand(E2.subs(vh, sol).subs(wh, sp.I * mu * uh))
    disp = sp.simplify(sp.expand(E2s / (sp.I * mu * uh)))
    # expected: (s + i(u0+2a)k)^2 - k^4 + (v0+2 lam) k^3/mu = 0
    expected = (s + sp.I * k * (u0 + 2 * a)) ** 2 - k ** 4 + (v0 + 2 * lam) * k ** 3 / mu
    # disp came out divided by k^2 (E2s was divided by i*mu*uh but not by k^2)
    ok = sp.expand(disp * k ** 2 - expected) == 0
    check("D2  semi-discrete: [sigma+i(u0+2a)k]^2 = k^4 - (v0+2*lam)k^3/mu   "
          "(mu = lattice symbol of discrete d/dy)", ok, "" if ok else f"got {sp.simplify(disp)}")
    return ok


