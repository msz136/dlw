def d4():
    """Lattice symbols of concrete y-schemes and their zero sets."""
    h, l = sp.symbols("h ell", positive=True)
    # CONVENTION (see spec section 2.0): the FULL symbol Lambda_h is what appears in D2's
    # relation  D^2 = k^4 - (v0+2 lam) k^3 / Lambda_h.  Here we list the NORMALISED symbol
    # r_h = Lambda_h / ell  (r_h -> 1 as h -> 0).  The two are related by Lambda_h = ell*r_h,
    # so the zero sets are IDENTICAL and the zero-mode conclusions are convention-free.
    # The i-form used in direction C,  D^2 = k^4 - i(v0+2 lam)k^3/mu_h  with mu_h := i*Lambda_h,
    # is the same statement.
    schemes = {
        "forward  (u_{j+1}-u_j)/h": (sp.exp(sp.I * l * h) - 1) / (sp.I * l * h),
        "backward (u_j-u_{j-1})/h": (1 - sp.exp(-sp.I * l * h)) / (sp.I * l * h),
        "centred  (u_{j+1}-u_{j-1})/(2h)": (sp.exp(sp.I * l * h) - sp.exp(-sp.I * l * h)) / (2 * sp.I * l * h),
    }
    print("    scheme                              r_h(ell) NORMALISED (= Lambda_h/ell)   zeros", flush=True)
    for name, mu in schemes.items():
        mu_s = sp.simplify(mu)
        zeros = sp.solve(sp.Eq(sp.simplify(mu_s), 0), l)
        print(f"    {name:<35} {str(mu_s):<35} {zeros}", flush=True)
    chk_forward = sp.simplify(sp.limit((sp.exp(sp.I * l * h) - 1) / (sp.I * l * h), l, 0))
    chk_centred = sp.simplify(
        sp.limit((sp.exp(sp.I * l * h) - sp.exp(-sp.I * l * h)) / (2 * sp.I * l * h), l, 0))
    ok = (chk_forward == 1) and (chk_centred == 1)
    check("D4  all three normalised symbols -> 1 as ell -> 0 (consistency)", ok)
    print("    NOTE: the CENTRED symbol is sin(ell h)/(ell h), which VANISHES at the", flush=True)
    print("          Nyquist mode ell h = pi (the checkerboard mode).  There the", flush=True)
    print("          dispersion relation degenerates: the (v0+2 lam) k^3 / mu term blows up.", flush=True)
    print("          The one-sided/staggered symbols do NOT vanish at Nyquist.", flush=True)
    centred_at_nyq = sp.simplify(
        ((sp.exp(sp.I * l * h) - sp.exp(-sp.I * l * h)) / (2 * sp.I * l * h)).subs(l, sp.pi / h))
    fwd_at_nyq = sp.simplify(((sp.exp(sp.I * l * h) - 1) / (sp.I * l * h)).subs(l, sp.pi / h))
    print(f"          centred symbol at Nyquist = {centred_at_nyq};  forward at Nyquist = {fwd_at_nyq}", flush=True)
    ok2 = (centred_at_nyq == 0)
    check("D4  centred differential operator has a spurious Nyquist/checkerboard zero mode", ok2)
    return ok and ok2


