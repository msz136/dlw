def d3():
    """
    The no-go statement: for fixed ell with mu_h(ell) finite and nonzero, and
    |k| -> infinity, the RHS behaves like k^4, hence |Re sigma| ~ |k|^2.
    The unstable branch is generated by the x-derivative structure (the k^4
    term); y-discretisation only rescales the 1/ell factor.
    """
    print("    argument: [s+i(u0+2a)k]^2 = k^4 - (v0+2 lam) k^3/mu", flush=True)
    print("    => s = -i(u0+2a)k +- k^2 sqrt(1 - (v0+2 lam)/(mu k))", flush=True)
    print("    => for fixed mu != 0 and |k| -> infinity:  s ~ -i(u0+2a)k +- k^2", flush=True)
    print("    => |Re s| ~ k^2 for ALL h, including h -> 0 and every consistent scheme.", flush=True)
    # numerical demonstration with the exact branch
    u0n, a_n, lam_n, v0n = 0.0, 0.0, -2.0, 4.0
    rows = []
    for mu in [3.0, 1.0, 0.3, 0.1]:
        for k in [1.0, 10.0, 100.0, 1000.0]:
            val = k ** 4 - (v0n + 2 * lam_n) * k ** 3 / mu
            # s + i(u0+2a)k = +- sqrt(val)
            import cmath
            r = cmath.sqrt(val)
            rows.append((mu, k, r.real))
    print("    mu      k        Re(sigma + i(u0+2a)k)", flush=True)
    for mu, k, re in rows:
        print(f"    {mu:<7} {k:<8} {re:.6g}", flush=True)
    # check the asymptotic ratio
    import cmath
    ok = True
    for mu in [3.0, 1.0, 0.3]:
        for k in [1000.0, 10000.0]:
            re = cmath.sqrt(k ** 4 - (v0n + 2 * lam_n) * k ** 3 / mu).real
            ratio = re / k ** 2
            if abs(ratio - 1.0) > 1e-2:
                ok = False
                print(f"    ratio off at mu={mu} k={k}: {ratio}", flush=True)
    check("D3  |Re sigma| / k^2 -> 1 for every fixed lattice symbol mu != 0 "
          "(ill-posedness is invariant under y-discretisation)", ok)
    return ok


