def analyze(path,out,animation=True):
    a=load_data(path);name=path.stem
    summaries=[];peaks=[];components=[];artifacts={};checks=[];sensitivity=[]
    for field in ("u","v"):
        artifact={};floor=100*np.finfo(float).eps*max(1.,float(np.max(np.abs(a[f"exact_{field}"]))))
        for it,t in enumerate(a["t"]):
            e=a[field][it]-a[f"exact_{field}"][it]
            p,kx,ky,stats=spectrum(e,a["dx"],a["dy"])
            raw,_,_,rawstats=spectrum(e,a["dx"],a["dy"],hann=False)
            signal=bool(np.max(np.abs(e))>floor)
            feats,comps,npos,nneg=detect_features(e,a["x"],a["y"],floor)
            common={"dataset":name,"field":field,"frame":it,"t":float(t)}
            row={**common,"rms_error":float(np.sqrt(np.mean(e**2))),"linf_error":float(np.max(np.abs(e))),
                "mean_error":float(np.mean(e)),"noise_floor":floor,"signal_above_floor":signal,
                "positive_extrema":npos,"negative_extrema":nneg,"excursion_components":len(comps),
                **stats,**spectrum_features(p,kx,ky,a["dx"],a["dy"],signal),
                **{"raw_"+k:v for k,v in spectrum_features(raw,kx,ky,a["dx"],a["dy"],signal).items()},
                "raw_parseval_relative_residual":rawstats["parseval_relative_residual"]}
            summaries.append(row)
            peaks.extend({**common,**q} for q in feats)
            components.extend({**common,"component":k,**q} for k,q in enumerate(comps,1))
            if stats["parseval_relative_residual"]>1e-12 or rawstats["parseval_relative_residual"]>1e-12:
                raise AssertionError("Parseval check failed")
            if it==len(a["t"])-1:
                c=wavelet_section(e,a["x"],a["y"])
                artifact={"peaks_final":feats,"components_final":comps,"wavelet":c,"final_metrics":row}
                for fraction in (.35,.5,.65):
                    _,cc,_,_=detect_features(e,a["x"],a["y"],floor,excursion_fraction=fraction)
                    sensitivity.append({**common,"excursion_threshold_fraction":fraction,
                        "number_components":len(cc),
                        "number_elongated":sum(q["aspect_ratio"]>=3 for q in cc),
                        "number_touching_boundary":sum(q["touches_boundary"] for q in cc),
                        "max_aspect_ratio":max((q["aspect_ratio"] for q in cc),default=np.nan),
                        "largest_component_cells":max((q["cells"] for q in cc),default=0)})
                np.savez_compressed(out/f"{name}_{field}_spectral_data.npz",x=a["x"],y=a["y"],kx=kx,ky=ky,
                    error=e,power_hann=p,power_rectangular=raw,cwt_power=c["power"],cwt_wavelength=c["wavelength"],
                    cwt_scales=c["scales"],cwt_edge_affected=c["edge_affected"],section_y=c["row_y"],
                    section=c["section_demeaned"],time=float(t))
        artifacts[field]=artifact
        checks.append({"field":field,"initial_linf_error":summaries[-len(a["t"])]["linf_error"],
            "initial_error_below_roundoff_floor":not summaries[-len(a["t"])]["signal_above_floor"],
            "max_parseval_relative_residual":max(r["parseval_relative_residual"] for r in summaries if r["field"]==field)})
    main="halfdt" not in name
    if main:
        plot_final(a,name,out,artifacts);plot_wavelets(a,name,out,artifacts)
        if animation: make_animation(a,name,out)
    info={"file":str(path.resolve()),"sha256":file_hash(path),"array_shape":list(a["u"].shape),
        "x_range":[float(a["x"][0]),float(a["x"][-1])],"y_range":[float(a["y"][0]),float(a["y"][-1])],
        "t_range":[float(a["t"][0]),float(a["t"][-1])],"dx":a["dx"],"dy":a["dy"],"checks":checks,
        "final":{f:{**artifacts[f]["final_metrics"],"section_y":artifacts[f]["wavelet"]["row_y"],
             **{k:v for k,v in artifacts[f]["wavelet"].items() if k.startswith("cwt_peak")},
             "components":artifacts[f]["components_final"][:10]} for f in ("u","v")}}
    return summaries,peaks,components,info,sensitivity


