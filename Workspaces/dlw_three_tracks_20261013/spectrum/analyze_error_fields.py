def file_hash(path):
    h = hashlib.sha256()
    with open(path, "rb") as stream:
        for b in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(b)
    return h.hexdigest()


def write_csv(path, rows):
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with path.open("w", newline="", encoding="utf-8-sig") as stream:
        w = csv.DictWriter(stream, fields)
        w.writeheader()
        w.writerows(rows)


def json_ready(value):
    """Keep undefined zero-error diagnostics as JSON null, never NaN tokens."""
    if isinstance(value, dict): return {k:json_ready(v) for k,v in value.items()}
    if isinstance(value, (list, tuple)): return [json_ready(v) for v in value]
    if isinstance(value, (float, np.floating)) and not np.isfinite(value): return None
    return value


def load_data(path):
    with np.load(path, allow_pickle=False) as d:
        a = {k: d[k].copy() for k in d.files}
    for key in ("x", "y", "t", "u", "v", "exact_u", "exact_v"):
        if key not in a:
            raise ValueError(f"{path.name} missing {key}")
    for key in ("x", "y", "t"):
        a[key] = np.asarray(a[key], dtype=float).ravel()
        if np.any(np.diff(a[key]) <= 0):
            raise ValueError(f"{key} not strictly increasing")
    for key in ("x", "y"):
        if not np.allclose(np.diff(a[key]), np.diff(a[key])[0], rtol=1e-10, atol=1e-12):
            raise ValueError(f"{key} must be uniform")
    expected = (len(a["t"]), len(a["y"]), len(a["x"]))
    for key in ("u", "v", "exact_u", "exact_v"):
        if a[key].shape != expected:
            raise ValueError(f"{key}: {a[key].shape} != {expected}")
        if not np.all(np.isfinite(a[key])):
            raise ValueError(f"Nonfinite {key}")
    a["dx"] = float(a["x"][1] - a["x"][0])
    a["dy"] = float(a["y"][1] - a["y"][0])
    return a


def spectrum(e, dx, dy, hann=True):
    """Two-sided power per DFT bin; sum equals corrected windowed mean square.

    F=FFT2(w*(e-weighted_mean))/N, P=|F|^2/mean(w^2).
    The DC is removed using weights w, not w^2. No radial shell averaging.
    Wave numbers are angular physical frequencies (radian/coordinate unit).
    """
    ny, nx = e.shape
    w = np.outer(np.hanning(ny), np.hanning(nx)) if hann else np.ones_like(e)
    mu = float(np.sum(w * e) / np.sum(w))
    g = w * (e - mu)
    correction = float(np.mean(w**2))
    f = np.fft.fftshift(np.fft.fft2(g) / e.size)
    p = np.abs(f)**2 / correction
    kx = np.fft.fftshift(2 * np.pi * np.fft.fftfreq(nx, d=dx))
    ky = np.fft.fftshift(2 * np.pi * np.fft.fftfreq(ny, d=dy))
    energy = float(np.mean(g**2) / correction)
    mismatch = abs(float(p.sum()) - energy) / max(energy, np.finfo(float).tiny)
    return p, kx, ky, {"removed_mean": mu, "window_energy_factor": correction,
        "power_total": float(p.sum()), "parseval_relative_residual": mismatch}


def spectrum_features(p, kx, ky, dx, dy, signal=True):
    total = float(p.sum())
    if not signal or total <= np.finfo(float).tiny:
        return {"dominant_kx": np.nan, "dominant_ky": np.nan,
            "high_k_fraction": np.nan, "kx_rms": np.nan, "ky_rms": np.nan}
    # Real fields give conjugate pairs. Report a deterministic half-plane member.
    self_y = np.isclose(ky,0,atol=1e-12)
    if len(ky)%2==0: self_y |= np.isclose(ky,-np.pi/dy,atol=1e-12)
    selected_x = kx >= -1e-12
    if len(kx)%2==0: selected_x |= np.isclose(kx,-np.pi/dx,atol=1e-12)
    half = (ky[:,None]>1e-12) | (self_y[:,None]&selected_x[None,:])
    half &= ~((np.abs(ky[:,None])<1e-12)&(np.abs(kx[None,:])<1e-12))
    j, i = np.unravel_index(np.argmax(np.where(half, p, -1)), p.shape)
    high = (np.abs(kx)[None, :] >= 0.5 * np.pi / dx) | (np.abs(ky)[:, None] >= 0.5 * np.pi / dy)
    return {"dominant_kx": float(kx[i]), "dominant_ky": float(ky[j]),
            "high_k_fraction": float(p[high].sum() / total),
            "kx_rms": float(np.sqrt(np.sum(p * kx[None, :]**2) / total)),
            "ky_rms": float(np.sqrt(np.sum(p * ky[:, None]**2) / total))}


def detect_features(e, x, y, noise_floor, excursion_fraction=0.5):
    """Grid-local extrema and |error| excursion components; no soliton claim.

    Peaks: 5x5 maximum filter, >=25% of frame Linf and above reference-scaled
    roundoff floor, exclude two cells at boundaries.  Save strongest 64/sign.
    Components: 8-connected |error| >=50% of frame Linf; >=4 grid cells.
    Physical covariance, aspect ratio and boundary contact identify ridges.
    """
    peak = float(np.max(np.abs(e)))
    if peak <= noise_floor:
        return [], [], 0, 0
    features, counts = [], []
    for sgn, sign in ((1, "positive"), (-1, "negative")):
        z = sgn * e
        mask = (z == ndimage.maximum_filter(z, size=5, mode="nearest")) & (z >= max(0.25*peak, noise_floor))
        mask[:2] = False; mask[-2:] = False
        mask[:, :2] = False; mask[:, -2:] = False
        # Collapse any exactly flat connected plateau to its strongest cell.
        labels, count = ndimage.label(mask, structure=np.ones((3, 3)))
        pts = []
        for lab in range(1, count+1):
            yy, xx = np.where(labels == lab)
            best = np.argmax(z[yy, xx]); j, i = int(yy[best]), int(xx[best])
            pts.append((float(z[j, i]), j, i))
        counts.append(len(pts))
        for rank, (_, j, i) in enumerate(sorted(pts, reverse=True)[:64], 1):
            features.append({"sign": sign, "rank": rank, "x": float(x[i]), "y": float(y[j]),
                "ix": i, "iy": j, "amplitude": float(e[j, i]),
                "threshold_abs": max(0.25*peak, noise_floor)})
    labels, count = ndimage.label(np.abs(e) >= max(excursion_fraction*peak, noise_floor), structure=np.ones((3, 3)))
    components = []
    for lab in range(1, count+1):
        yy, xx = np.where(labels == lab)
        if len(xx) < 4:
            continue
        weights = np.abs(e[yy, xx]); weights = weights / weights.sum()
        coords = np.stack((x[xx], y[yy]), axis=1)
        center = np.sum(weights[:, None] * coords, axis=0)
        centered = coords-center
        cov = (centered * weights[:, None]).T @ centered
        eigvals, eigvecs = np.linalg.eigh(cov)
        values = np.maximum(eigvals, 0)
        # Grid variance floor prevents a one-cell ridge being assigned infinity.
        floor = min(float(x[1]-x[0]), float(y[1]-y[0]))**2 / 12
        ratio = float(np.sqrt((values[1]+floor)/(values[0]+floor)))
        components.append({"cells": len(xx), "center_x": float(center[0]), "center_y": float(center[1]),
            "aspect_ratio": ratio, "major_std": float(np.sqrt(values[1])),
            "minor_std": float(np.sqrt(values[0])),
            "orientation_degrees": float(np.degrees(np.arctan2(eigvecs[1,1],eigvecs[0,1]))),
            "excursion_threshold_fraction": excursion_fraction,
            "touches_boundary": bool(np.any((xx==0)|(yy==0)|(xx==len(x)-1)|(yy==len(y)-1))),
            "abs_peak": float(np.max(np.abs(e[yy,xx]))),
            "signed_mean": float(np.mean(e[yy,xx])),
            "morphology": "elongated excursion" if ratio >= 3 else "compact excursion"})
    components.sort(key=lambda c:c["abs_peak"], reverse=True)
    return features, components, counts[0], counts[1]


def wavelet_section(e, x, y):
    """An x-direction section at the common native row closest to y=0.

    Morlet cmor1.5-1.0, scales >=4 cells (avoid near-Nyquist aliasing).
    Demean, no Hann window. PyWavelets zero extension; shade a conservative
    e^-2 amplitude margin sqrt(2*B)*scale*dx around both ends. Power is |CWT|^2/scale;
    it is a diagnostic scalogram, not a Parseval-normalized PSD.
    """
    j = int(np.argmin(np.abs(y)))
    z = e[j].copy(); z -= z.mean()
    scales = np.geomspace(4., max(4.01, min(len(x)/3, 128.)), 64)
    coeff, freq = pywt.cwt(z, scales, "cmor1.5-1.0", sampling_period=float(x[1]-x[0]), method="fft")
    power = np.abs(coeff)**2 / scales[:, None]
    wavelength = 1/freq
    edge_distance = np.minimum(x-x[0], x[-1]-x)
    affected = edge_distance[None, :] < (np.sqrt(2*1.5)*scales[:, None]*(x[1]-x[0]))
    valid = np.where(affected, np.nan, power)
    if np.any(np.isfinite(valid)) and np.nanmax(valid)>0:
        si, xi = np.unravel_index(np.nanargmax(valid), valid.shape)
        peak = {"cwt_peak_x": float(x[xi]), "cwt_peak_wavelength": float(wavelength[si]),
                "cwt_peak_power": float(power[si,xi])}
    else:
        peak = {"cwt_peak_x": np.nan, "cwt_peak_wavelength": np.nan, "cwt_peak_power": np.nan}
    return {"row_index":j, "row_y":float(y[j]), "section_demeaned":z,
            "scales":scales, "wavelength":wavelength, "power":power,
            "edge_affected":affected, **peak}


