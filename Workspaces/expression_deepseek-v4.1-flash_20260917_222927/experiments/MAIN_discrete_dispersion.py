"""
MAIN-AGENT CROSS-CUTTING ANALYSIS:
why no consistent y-discretisation can remove the ill-posedness.

Run: python -u experiments/MAIN_discrete_dispersion.py

Sections
  D1  continuous linearisation (re-derivation, independent of MAIN_verify_core)
  D2  general semi-discrete linearisation: the y-operator enters ONLY through a
      bounded lattice symbol mu_h(ell); derive the general discrete relation
  D3  the no-go statement, and a numerical demonstration of the retained k^2 growth
  D4  specific schemes: forward, backward, centred (with its EXTRA Nyquist
      pathology), and the staggered two-tau scheme
  D5  what the zero modes do (ell -> 0 and the centred checkerboard mode)
"""

import sympy as sp

FAIL = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}" + (f"   {detail}" if detail else ""), flush=True)
    if not ok:
        FAIL.append(name)


# ----------------------------------------------------------------------------
def d1():
    """Continuous linearisation, re-derived."""
    u0, v0, a, lam, k, l, s = sp.symbols("u0 v0 a lambda k ell sigma")
    uh, vh = sp.symbols("uh vh")
    # (1) u_yt + v_xx + u u_xy + u_x u_y + 2a u_xy
    # mode e^{sigma t + i(kx + ell y)}; u_x u_y is O(eps^2) about a constant bg
    E1 = uh * s * sp.I * l + vh * (sp.I * k) ** 2 + uh * u0 * (sp.I * k) * (sp.I * l) \
        + 2 * a * uh * (sp.I * k) * (sp.I * l)
    # (2) v_t + (uv)_x + u_xxy + 2a v_x + 2 lam u_x
    E2 = vh * s + sp.I * k * (v0 * uh + u0 * vh) + uh * (sp.I * k) ** 2 * (sp.I * l) \
        + 2 * a * sp.I * k * vh + 2 * lam * sp.I * k * uh
    E1, E2 = sp.expand(E1), sp.expand(E2)
    sol = sp.solve(sp.Eq(E1, 0), vh)[0]
    disp = sp.simplify(sp.expand(E2.subs(vh, sol) * k ** 2 / (sp.I * uh * l)))
    expected = (s + sp.I * k * (u0 + 2 * a)) ** 2 - k ** 4 + (v0 + 2 * lam) * k ** 3 / l
    check("D1  continuous: [sigma+i(u0+2a)k]^2 = k^4 - (v0+2*lam)k^3/ell",
          sp.expand(disp - expected) == 0)
    return disp


