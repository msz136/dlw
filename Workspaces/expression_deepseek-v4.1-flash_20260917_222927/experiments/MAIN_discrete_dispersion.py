def d5():
    """Zero-mode sectors."""
    u0, v0, a, lam, k, l, s = sp.symbols("u0 v0 a lambda k ell sigma")
    uh, vh = sp.symbols("uh vh")
    E1 = sp.expand(uh * (s * sp.I * l + u0 * (sp.I * k) * (sp.I * l) + 2 * a * (sp.I * k) * (sp.I * l))
                   + vh * (sp.I * k) ** 2)
    E2 = sp.expand(vh * (s + sp.I * k * u0 + 2 * a * sp.I * k)
                   + uh * (sp.I * k * v0 + 2 * lam * sp.I * k + (sp.I * k) ** 2 * (sp.I * l)))
    print("    ell = 0 (y-independent) sector:", flush=True)
    print("      E1:", sp.simplify(E1.subs(l, 0)), flush=True)
    print("      E2:", sp.simplify(E2.subs(l, 0)), flush=True)
    print("      => vh = 0 and uh*(v0 + 2 lam) = 0", flush=True)
    print("      => NO nontrivial y-independent linear mode unless v0 = -2 lam;", flush=True)
    print("         at v0 = -2 lam the exact solution v = -2 lam, u = U(x,t) is a", flush=True)
    print("         genuine infinite-dimensional zero mode (verified in MAIN_verify_core V7).", flush=True)
    ok = sp.simplify(E1.subs(l, 0) + k ** 2 * vh) == 0
    check("D5  ell=0 sector forces vh=0 and uh*(v0+2*lam)=0", ok)
    return ok


