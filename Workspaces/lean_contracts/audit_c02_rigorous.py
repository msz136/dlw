def main():
    M = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    amod = int(sys.argv[2]) if len(sys.argv) > 2 else 7
    p = 32003
    Rf, Ef, c1f, c2f = setup(M, amod, p)
    vars_ = sorted(set().union(Rf.free_symbols, Ef.free_symbols,
                               c1f.free_symbols, c2f.free_symbols),
                   key=lambda s: s.name)
    print('M=%d a=%d  quotient variables: %d' % (M, amod, len(vars_)))
    print('R  =', Rf)
    print('E2 =', Ef)
    print('c1 =', c1f)
    print('c2 =', c2f)

    def is_member(f, gens):
        """Is f in the ideal generated by gens, inside the quotient ring?
        Decided by the normal form of the S-polynomial-free 'division':
        we use sympy groebner but on the quotient ring variables only, which is
        legitimate because Clairaut has already been imposed."""
        G = sp.groebner(list(gens), *vars_, modulus=p, order='grevlex')
        out = G.reduce(f)
        r = out[0] if isinstance(out, tuple) else out
        r = sp.expand(r[0] if isinstance(r, list) else r)
        return r

    # sanity checks of the membership routine itself
    print('\n-- sanity --')
    print('R in <R> :', is_member(Rf, [Rf]))
    print('c1 in <R> :', is_member(c1f, [Rf]))
    print('c1 in <E2>:', is_member(c1f, [Ef]))
    print('c1 in <R,E2>:', is_member(c1f, [Rf, Ef]))
    print('c2 in <R,E2>:', is_member(c2f, [Rf, Ef]))
    print('(c1*c2+c1) in <R,E2>:', is_member(sp.expand(c1f * c2f + c1f), [Rf, Ef]))


if __name__ == '__main__':
    main()
